USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS learn_wh
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE learn_wh;

CREATE DATABASE IF NOT EXISTS retail_db;
CREATE SCHEMA IF NOT EXISTS retail_db.raw;
CREATE SCHEMA IF NOT EXISTS retail_db.staging;
CREATE SCHEMA IF NOT EXISTS retail_db.mart;

USE SCHEMA retail_db.raw;

CREATE OR REPLACE FILE FORMAT csv_ff
  TYPE = CSV
  PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL');

CREATE OR REPLACE STAGE raw_stage FILE_FORMAT = csv_ff;
LIST @raw_stage;

