SELECT table_name,
       LISTAGG(column_name || ' (' || data_type || ')', ', ')
         WITHIN GROUP (ORDER BY ordinal_position) AS columns_list
FROM retail_db.information_schema.columns
WHERE table_schema = 'RAW'
GROUP BY table_name
ORDER BY table_name;